// The wizard's spells as weapons of the real 5010 table: Fireball 25, Lightning Storm 26, Ice Field 27. Their base
// damage spans the armour columns units really wear (the "-" columns are unused), before the wizard's rating, the
// target's terrain cover and Formation; the reach is the weapon's own [min, max] range.
export const SPELL_WEAPON = { fireball: 25, lightning: 26, ice: 27 };
export function spellStats(spell) {
  const weapon = SPELL_WEAPON[spell] || 25;
  const row = WEAPON_DMG[weapon] || [];
  const worn = row.filter((v, i) => i !== 13 && i !== 14 && v > 0); // 13–14 are building materials
  const [min, max] = WEAPON_RANGE[weapon] || [2, 7];
  const shares = BLAST_SHARE[weapon] || [100];
  return { lo: Math.min(...worn), hi: Math.max(...worn), min, max, splash: shares[1] != null ? shares[1] : shares[0] };
}
